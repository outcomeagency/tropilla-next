export function getPortalDict(locale: Locale): PortalDict {
  return PORTAL[locale];
}

/** Textos del formulario de contacto sin funciones (se pasan a un Client Component). */
export function contactDict(t: PortalDict): Omit<PortalDict["contact"], "about"> {
  // eslint-disable-next-line @typescript-eslint/no-unused-vars
  const { about, ...rest } = t.contact;
  return rest;
}
